local T = ...
local CS = require("novarr.checkstate")

local POLL, MAX = CS.POLL_S, CS.MAX_S

T.it("start: a running check on the server is joined, anything else asks for one", function()
    T.eq(CS.startAction({ status = "running" }), "join")
    for _i, s in ipairs({ "idle", "done", "failed" }) do T.eq(CS.startAction({ status = s }), "post") end
    T.eq(CS.startAction(nil), "post")
end)

T.it("running -> poll every 15 s, then done with N new chapters", function()
    local st = CS.new(1000)
    T.truthy(CS.active(st))
    T.eq(CS.onAnswer(st, { status = "running" }, 1000), "poll")
    T.eq(st.phase, "running")
    T.eq(CS.nextDelay(st, 1000), POLL)
    T.eq(CS.text(st), "Checking for new chapters…")
    T.eq(CS.onAnswer(st, { status = "running" }, 1015), "poll")
    T.eq(CS.onAnswer(st, { status = "done", new_chapters = 3, chapters_now = 123 }, 1030), "stop")
    T.eq(st.phase, "done")
    T.falsy(CS.active(st))
    T.eq(st.new_chapters, 3)
    T.eq({ CS.text(st) }, { "3 new chapters.", "new" })
end)

T.it("done texts: none, one, unknown count", function()
    local st = CS.new(0)
    CS.onAnswer(st, { status = "done", new_chapters = 0 }, 5)
    T.eq({ CS.text(st) }, { "No new chapters yet.", "none" })
    st = CS.new(0)
    CS.onAnswer(st, { status = "done", new_chapters = 1 }, 5)
    T.eq(CS.text(st), "1 new chapter.")
    st = CS.new(0)
    CS.onAnswer(st, { status = "done", new_chapters = -4 }, 5)
    T.eq(st.new_chapters, 0, "never negative")
end)

T.it("the server answers done straight away (sync queue)", function()
    local st = CS.new(0)
    T.eq(CS.onAnswer(st, { status = "done", new_chapters = 2 }, 0), "stop")
    T.eq(st.phase, "done")
end)

T.it("failed: the server's message, in plain words", function()
    local st = CS.new(0)
    CS.onAnswer(st, { status = "running" }, 0)
    T.eq(CS.onAnswer(st, { status = "failed", message = "Another scrape of this novel is running." }, 15), "stop")
    T.eq({ CS.text(st) }, { "The check didn't work: Another scrape of this novel is running.", "failed" })
    st = CS.new(0)
    CS.onAnswer(st, { status = "failed" }, 0)
    T.eq(CS.text(st), "The check didn't work. Try again later.")
end)

T.it("joined: says so", function()
    local st = CS.new(0)
    T.eq(CS.onAnswer(st, { status = "running" }, 0, { joined = true }), "poll")
    T.truthy(st.joined)
    T.contains(CS.text(st), "already running")
end)

T.it("timeout: still running after 10 minutes -> stop, plain text", function()
    local st = CS.new(0)
    CS.onAnswer(st, { status = "running" }, 0)
    T.eq(CS.onAnswer(st, { status = "running" }, MAX - 1), "poll")
    T.eq(CS.nextDelay(st, MAX - 1), 1, "the last poll lands on the deadline")
    T.eq(CS.onAnswer(st, { status = "running" }, MAX), "stop")
    T.eq(st.phase, "timeout")
    T.contains(CS.text(st), "still checking")
    T.eq(CS.nextDelay(st, MAX + 50), 0)
end)

T.it("idle while polling: done when it was seen running, else it never started", function()
    local st = CS.new(0)
    CS.onAnswer(st, { status = "running" }, 0)
    T.eq(CS.onAnswer(st, { status = "idle" }, 15), "stop")
    T.eq(st.phase, "done")
    T.eq(st.new_chapters, nil)
    T.eq(CS.text(st), "The check is done.")
    st = CS.new(0)
    T.eq(CS.onAnswer(st, { status = "idle" }, 0), "stop")
    T.eq(st.phase, "failed")
end)

T.it("errors: before the start stop at once; while polling keep going until the deadline", function()
    local st = CS.new(0)
    T.eq(CS.onError(st, { kind = "offline" }, 0), "stop")
    T.eq(st.phase, "error")
    T.eq(CS.text(st), nil, "the caller words network errors")
    st = CS.new(0)
    CS.onAnswer(st, { status = "running" }, 0)
    T.eq(CS.onError(st, { kind = "offline" }, 15), "poll")
    T.eq(CS.onError(st, { kind = "server", status = 500 }, 30), "poll")
    T.eq(st.phase, "running")
    T.eq(CS.onAnswer(st, { status = "running" }, 45), "poll")
    T.eq(st.errors, 0, "an answer clears the error count")
    T.eq(CS.onError(st, { kind = "offline" }, MAX), "stop")
    T.eq(st.phase, "timeout")
end)

T.it("errors: two not-found answers while polling end it (novel removed)", function()
    local st = CS.new(0)
    CS.onAnswer(st, { status = "running" }, 0)
    T.eq(CS.onError(st, { kind = "not_found" }, 15), "poll")
    T.eq(CS.onError(st, { kind = "not_found" }, 30), "stop")
    T.eq(st.phase, "error")
end)

T.it("an unknown status or a broken answer is treated as an error", function()
    local st = CS.new(0)
    CS.onAnswer(st, { status = "running" }, 0)
    T.eq(CS.onAnswer(st, { status = "weird" }, 15), "poll")
    T.eq(CS.onAnswer(st, "junk", 30), "poll")
    T.eq(st.phase, "running")
end)

T.it("no state: no text", function()
    T.eq(CS.text(nil), nil)
    T.falsy(CS.active(nil))
end)
