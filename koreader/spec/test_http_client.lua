local T = ...
local H = require("novarr.http_client")

-- URL / port handling
T.it("parseUrl: default ports, explicit ports, path and origin", function()
    local u = H.parseUrl("https://Nas.Example.ts.net/api/v1/meta?x=1#f")
    T.eq(u.scheme, "https")
    T.eq(u.host, "nas.example.ts.net")
    T.eq(u.port, 443)
    T.eq(u.path, "/api/v1/meta?x=1")
    T.eq(u.origin, "https://nas.example.ts.net")
    u = H.parseUrl("http://127.0.0.1:8137")
    T.eq(u.port, 8137)
    T.eq(u.path, "/")
    T.eq(u.origin, "http://127.0.0.1:8137")
    T.eq(H.parseUrl("http://h:80/x").origin, "http://h", "default port left out of the origin")
    T.eq(H.parseUrl("https://h:443").origin, "https://h")
    T.eq(H.parseUrl("https://h:8443").port, 8443)
    T.eq(H.parseUrl("http://h?q=1").path, "/?q=1")
end)

T.it("parseUrl: IPv6 hosts keep their brackets in the origin only", function()
    local u = H.parseUrl("https://[fd7a:115c::1]:8443/x")
    T.eq(u.host, "fd7a:115c::1")
    T.eq(u.port, 8443)
    T.eq(u.origin, "https://[fd7a:115c::1]:8443")
end)

T.it("parseUrl: refuses what is not an absolute http(s) URL", function()
    for _i, bad in ipairs({ "ftp://h", "h:80", "http://", "http://h:0", "http://h:70000", "http://h:x", "http://u@h", 42 }) do
        T.eq(H.parseUrl(bad), nil, tostring(bad))
    end
end)

T.it("proxyAddress: KOReader's proxy setting, with or without scheme", function()
    local h, p = H.proxyAddress("http://127.0.0.1:1056")
    T.eq(h, "127.0.0.1"); T.eq(p, 1056)
    h, p = H.proxyAddress("127.0.0.1:1056")
    T.eq(h, "127.0.0.1"); T.eq(p, 1056)
    h, p = H.proxyAddress("http://proxy.lan")
    T.eq(h, "proxy.lan"); T.eq(p, 3128, "socket.http's default proxy port")
    h, p = H.proxyAddress("http://user:pw@proxy.lan:8080/")
    T.eq(h, "proxy.lan"); T.eq(p, 8080)
    h, p = H.proxyAddress("http://[::1]:1056")
    T.eq(h, "::1"); T.eq(p, 1056)
    T.eq(H.proxyAddress("https://proxy:443"), nil, "an https proxy is not supported")
    T.eq(H.proxyAddress(""), nil)
    T.eq(H.proxyAddress(nil), nil)
    T.eq(H.proxyAddress("http://proxy:99999"), nil)
end)

T.it("connectRequest: CONNECT line and Host header", function()
    local req = H.connectRequest("nas.example.ts.net", 443, "NovarrKOReader/1.3.0")
    T.contains(req, "CONNECT nas.example.ts.net:443 HTTP/1.1\r\n")
    T.contains(req, "\r\nHost: nas.example.ts.net:443\r\n")
    T.contains(req, "\r\nUser-Agent: NovarrKOReader/1.3.0\r\n")
    T.eq(req:sub(-4), "\r\n\r\n", "ends with the blank line")
    T.contains(H.connectRequest("fd7a::1", 8443), "CONNECT [fd7a::1]:8443 HTTP/1.1\r\nHost: [fd7a::1]:8443\r\n")
end)

T.it("parseStatusLine: proxy answers", function()
    T.eq({ H.parseStatusLine("HTTP/1.1 200 Connection established") }, { 200, "Connection established" })
    T.eq({ H.parseStatusLine("HTTP/1.0 200 OK\r") }, { 200, "OK" })
    T.eq({ H.parseStatusLine("HTTP/1.1 403 Forbidden") }, { 403, "Forbidden" })
    T.eq({ H.parseStatusLine("HTTP/2 407") }, { 407, "" })
    T.eq(H.parseStatusLine("SSH-2.0-OpenSSH"), nil)
    T.eq(H.parseStatusLine(""), nil)
    T.eq(H.parseStatusLine(nil), nil)
end)

T.it("resolveLocation: absolute, scheme-relative, absolute and relative paths", function()
    local cur = "https://h:8443/api/v1/novels/2?x=1"
    T.eq(H.resolveLocation(cur, "http://other/x"), "http://other/x")
    T.eq(H.resolveLocation(cur, "//other/y"), "https://other/y")
    T.eq(H.resolveLocation(cur, "/storage/c.jpg"), "https://h:8443/storage/c.jpg")
    T.eq(H.resolveLocation(cur, "chapters"), "https://h:8443/api/v1/novels/chapters")
    T.eq(H.resolveLocation(cur, "../meta"), "https://h:8443/api/v1/meta")
    T.eq(H.resolveLocation(cur, "./a/b/"), "https://h:8443/api/v1/novels/a/b/")
    T.eq(H.resolveLocation(cur, "/a/../b?q=2"), "https://h:8443/b?q=2")
    T.eq(H.resolveLocation(cur, "  "), nil)
    T.eq(H.resolveLocation("http://h", "x"), "http://h/x")
end)

T.it("shouldFollow: redirect codes, GET/HEAD only, never with a body", function()
    for _i, code in ipairs({ 301, 302, 303, 307, 308 }) do
        T.truthy(H.shouldFollow(code, "GET", false, "/x"), code)
    end
    T.truthy(H.shouldFollow(302, nil, false, "/x"), "default method GET")
    T.truthy(H.shouldFollow(302, "HEAD", false, "/x"))
    T.falsy(H.shouldFollow(302, "POST", false, "/x"))
    T.falsy(H.shouldFollow(302, "GET", true, "/x"))
    T.falsy(H.shouldFollow(200, "GET", false, "/x"))
    T.falsy(H.shouldFollow(304, "GET", false, "/x"))
    T.falsy(H.shouldFollow(302, "GET", false, nil))
    T.falsy(H.shouldFollow(302, "GET", false, " "))
end)
