local T = ...
local SS = require("novarr.searchstate")

local POLL, MAX = SS.POLL_S, SS.MAX_S
local RESULT = { items = { { title = "A", url = "u" } }, page = 1, has_more = false }

T.it("POST running -> poll every 3 s -> done with the result", function()
    local st = SS.new(100)
    T.truthy(SS.active(st))
    T.eq(SS.onStart(st, { id = "abc", status = "running" }, nil, 100), "poll")
    T.eq(st.phase, "running")
    T.eq(st.id, "abc")
    T.eq(SS.nextDelay(st, 100), POLL)
    T.eq(SS.onPoll(st, { id = "abc", status = "running" }, nil, 103), "poll")
    T.eq(SS.onPoll(st, { id = "abc", status = "done", result = RESULT }, nil, 106), "done")
    T.eq(st.phase, "done")
    T.eq(st.polls, 2)
    T.eq(st.result, RESULT)
    T.falsy(SS.active(st))
end)

T.it("an answer done straight away (cached on the server)", function()
    local st = SS.new(0)
    T.eq(SS.onStart(st, { id = "x", status = "done", result = RESULT }, nil, 0), "done")
    T.eq(st.result, RESULT)
end)

T.it("done without a result counts as failed", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    T.eq(SS.onPoll(st, { id = "x", status = "done" }, nil, 3), "stop")
    T.eq(st.phase, "failed")
end)

T.it("failed: the server's plain message", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    T.eq(SS.onPoll(st, { id = "x", status = "failed", message = "The source took too long." }, nil, 3), "stop")
    T.eq(st.phase, "failed")
    T.eq(SS.failureText(st), "The source took too long.")
    st = SS.new(0)
    SS.onStart(st, { id = "x", status = "failed" }, nil, 0)
    T.contains(SS.failureText(st), "didn't answer")
end)

T.it("404 or 405 on the POST: an older server, fall back to the blocking browse", function()
    local st = SS.new(0)
    T.eq(SS.onStart(st, nil, { kind = "not_found", status = 404 }, 0), "fallback")
    T.eq(st.phase, "fallback")
    st = SS.new(0)
    T.eq(SS.onStart(st, nil, { kind = "invalid", status = 405 }, 0), "fallback")
    T.truthy(SS.notSupported({ kind = "invalid", status = 405 }))
    T.falsy(SS.notSupported({ kind = "invalid", status = 422 }))
    T.falsy(SS.notSupported({ kind = "offline" }))
end)

T.it("other POST errors stop at once (the caller words them)", function()
    for _i, e in ipairs({ { kind = "offline" }, { kind = "invalid", status = 422, message = "q required" }, { kind = "server", status = 500 } }) do
        local st = SS.new(0)
        T.eq(SS.onStart(st, nil, e, 0), "stop")
        T.eq(st.phase, "error")
        T.eq(st.error, e)
        T.eq(SS.failureText(st), nil)
    end
end)

T.it("a running answer without an id cannot be followed", function()
    local st = SS.new(0)
    T.eq(SS.onStart(st, { status = "running" }, nil, 0), "stop")
    T.eq(st.phase, "error")
end)

T.it("network errors while polling: tried again until the limit, then timeout", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    T.eq(SS.onPoll(st, nil, { kind = "offline" }, 3), "poll")
    T.eq(SS.onPoll(st, nil, { kind = "server", status = 500 }, 6), "poll")
    T.eq(st.errors, 2)
    T.eq(SS.onPoll(st, { id = "x", status = "running" }, nil, 9), "poll")
    T.eq(st.errors, 0)
    T.eq(SS.onPoll(st, nil, { kind = "offline" }, MAX), "stop")
    T.eq(st.phase, "timeout")
    T.contains(SS.failureText(st), "took too long")
end)

T.it("404 while polling: the server forgot it (failed, plain words)", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    T.eq(SS.onPoll(st, nil, { kind = "not_found", status = 404 }, 3), "stop")
    T.eq(st.phase, "failed")
    T.contains(SS.failureText(st), "lost track")
end)

T.it("still running at the limit: timeout", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    T.eq(SS.onPoll(st, { id = "x", status = "running" }, nil, MAX - 1), "poll")
    T.eq(SS.nextDelay(st, MAX - 1), 1)
    T.eq(SS.onPoll(st, { id = "x", status = "running" }, nil, MAX), "stop")
    T.eq(st.phase, "timeout")
    T.eq(SS.nextDelay(st, MAX + 5), 0)
end)

T.it("offline polls (never prompting) wait until the limit", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    T.eq(SS.onOffline(st, 10), "poll")
    T.eq(SS.onOffline(st, MAX + 1), "stop")
    T.eq(st.phase, "timeout")
end)

T.it("cancel stops following; later answers are ignored", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    SS.cancel(st)
    T.eq(st.phase, "cancelled")
    T.falsy(SS.active(st))
    T.eq(SS.onPoll(st, { id = "x", status = "done", result = RESULT }, nil, 3), "stop")
    T.eq(st.result, nil)
    T.eq(SS.onOffline(st, 3), "stop")
    T.eq(SS.failureText(st), nil)
    -- Cancelling something that already ended changes nothing.
    local done = SS.new(0)
    SS.onStart(done, { id = "y", status = "done", result = RESULT }, nil, 0)
    SS.cancel(done)
    T.eq(done.phase, "done")
end)

T.it("an unknown status counts as failed", function()
    local st = SS.new(0)
    SS.onStart(st, { id = "x", status = "running" }, nil, 0)
    T.eq(SS.onPoll(st, { id = "x", status = "weird" }, nil, 3), "stop")
    T.eq(st.phase, "failed")
end)
